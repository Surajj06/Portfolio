import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { getDocument } from 'pdfjs-dist/legacy/build/pdf.mjs';

// Only these intentionally public documents become assistant knowledge.
// Never scan the repository, environment files, or visitors' uploads.
const root = fileURLToPath(new URL('../', import.meta.url));
const documents = [];

function add(title, text, url) {
  const clean = text.replace(/\s+/g, ' ').trim();
  if (!clean) throw new Error(`No readable text in ${title}. Supply a text-based document.`);
  // Bounded, overlapping passages keep local lexical retrieval useful.
  let start = 0;
  while (start < clean.length) {
    let end = Math.min(start + 850, clean.length);
    if (end < clean.length) end = clean.lastIndexOf(' ', end);
    if (end <= start) end = Math.min(start + 850, clean.length);
    documents.push({ title, text: clean.slice(start, end), url });
    if (end === clean.length) break;
    start = Math.max(start + 1, end - 100);
    const nextSpace = clean.indexOf(' ', start);
    if (nextSpace >= 0 && nextSpace < end) start = nextSpace + 1;
  }
}

async function readPdf(filename, title, url) {
  const pdf = await getDocument({ data: new Uint8Array(await readFile(filename)), useSystemFonts: true, isEvalSupported: false }).promise;
  try {
    for (let n = 1; n <= pdf.numPages; n++) {
      const content = await (await pdf.getPage(n)).getTextContent();
      add(`${title} — page ${n}`, content.items.map(item => 'str' in item ? item.str : '').join(' '), url);
    }
  } finally {
    await pdf.destroy();
  }
}

await readPdf(path.join(root, 'src/assets/resume.pdf'), 'Suraj Jha resume', '/assets/resume.pdf');
const folder = path.join(root, 'knowledge');
await mkdir(folder, { recursive: true });
for (const entry of (await readdir(folder, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
  if (!entry.isFile() || entry.name.toLowerCase() === 'readme.md') continue;
  const filename = path.join(folder, entry.name);
  if (/\.pdf$/i.test(entry.name)) await readPdf(filename, entry.name);
  else if (/\.(md|txt)$/i.test(entry.name)) add(entry.name, await readFile(filename, 'utf8'));
}

await writeFile(path.join(root, 'api/_documents.ts'), `// Generated by npm run knowledge. Do not edit by hand.\nexport const DOCUMENTS: { title: string; text: string; url?: string }[] = ${JSON.stringify(documents, null, 2)};\n`);
console.log(`Indexed ${documents.length} document passages for the assistant.`);
